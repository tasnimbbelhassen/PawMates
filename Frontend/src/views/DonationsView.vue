<script setup>
import { ref, computed, onMounted, watch } from 'vue'
import { donationsAPI } from '../services/api'
import { useAuthStore } from '../stores/authStore'
import NavBar from '../components/NavBar.vue'

const authStore = useAuthStore()
const tab = ref('sent')
const donations = ref([])
const loading = ref(false)

const totalDonations = computed(() => donations.value.length)
const totalAmount = computed(() => donations.value.reduce((sum, d) => sum + (d.amount || 0), 0))

const fetchDonations = async () => {
  loading.value = true
  try {
    const res = tab.value === 'sent' 
      ? await donationsAPI.getMyDonations() 
      : await donationsAPI.getReceived()
    donations.value = res.data
  } catch (error) {
    console.error('Erreur chargement dons:', error)
  } finally {
    loading.value = false
  }
}

const formatDate = (date) => {
  if (!date) return ''
  return new Date(date).toLocaleDateString('fr-FR', { day: 'numeric', month: 'short', year: 'numeric' })
}

watch(tab, fetchDonations)
onMounted(fetchDonations)
</script>

