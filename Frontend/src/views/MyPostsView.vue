<script setup>
import { ref, computed, onMounted } from 'vue'
import { useRouter } from 'vue-router'
import { postsAPI } from '../services/api'
import { useAuthStore } from '../stores/authStore'
import NavBar from '../components/NavBar.vue'

const router = useRouter()
const authStore = useAuthStore()
const posts = ref([])
const loading = ref(true)
const activeMenu = ref(null)

const activePosts = computed(() => posts.value.filter(p => p.status === 'available'))
const closedPosts = computed(() => posts.value.filter(p => p.status !== 'available'))

const toggleMenu = (postId) => {
  if (activeMenu.value === postId) {
    activeMenu.value = null
  } else {
    activeMenu.value = postId
  }
}

const editPost = (postId) => {
  activeMenu.value = null
  router.push(`/posts/${postId}/edit`)
}

const closePost = async (postId) => {
  activeMenu.value = null
  if (!confirm('Fermer cette annonce ? Une fois fermée, elle ne sera plus visible.')) return
  try {
    await postsAPI.close(postId)
    const post = posts.value.find(p => p.id === postId)
    if (post) post.status = 'closed'
  } catch (e) {
    alert(e.response?.data?.message || 'Erreur lors de la fermeture')
  }
}

const deletePost = async (postId) => {
  activeMenu.value = null
  if (!confirm('Supprimer définitivement cette annonce ? Cette action est irréversible.')) return
  try {
    await postsAPI.delete(postId)
    posts.value = posts.value.filter(p => p.id !== postId)
  } catch (e) {
    alert(e.response?.data?.message || 'Erreur lors de la suppression')
  }
}

onMounted(async () => {
  try {
    const res = await postsAPI.getMyPosts()
    posts.value = res.data
  } finally {
    loading.value = false
  }
})

const formatDate = (date) => {
  if (!date) return ''
  return new Date(date).toLocaleDateString('fr-FR', { day: 'numeric', month: 'short', year: 'numeric' })
}

const statusLabel = (status) => {
  const labels = { closed: 'Fermée', adopted: 'Adoptée', removed: 'Supprimée', available: 'Disponible' }
  return labels[status] || status
}
</script>

