<script setup>
import { ref, computed, onMounted, watch } from 'vue'
import { adoptionAPI } from '../services/api'
import { useAuthStore } from '../stores/authStore'
import NavBar from '../components/NavBar.vue'

const authStore = useAuthStore()
const tab = ref('received')
const requests = ref([])
const loading = ref(false)

const pendingCount = computed(() => {
  if (tab.value === 'received') {
    return requests.value.filter(r => r.status === 'pending').length
  }
  return 0
})

const fetchRequests = async () => {
  loading.value = true
  try {
    const res = tab.value === 'received' 
      ? await adoptionAPI.getReceived() 
      : await adoptionAPI.getSent()
    requests.value = res.data
  } catch (error) {
    console.error('Erreur chargement demandes:', error)
  } finally {
    loading.value = false
  }
}

const accept = async (id) => {
  await adoptionAPI.accept(id)
  fetchRequests()
}

const reject = async (id) => {
  await adoptionAPI.reject(id)
  fetchRequests()
}

const cancel = async (id) => {
  await adoptionAPI.cancel(id)
  fetchRequests()
}

const formatDate = (date) => {
  if (!date) return ''
  const now = new Date()
  const d = new Date(date)
  const diffMs = now - d
  const diffMins = Math.floor(diffMs / 60000)
  const diffHours = Math.floor(diffMs / 3600000)
  const diffDays = Math.floor(diffMs / 86400000)
  
  if (diffMins < 1) return 'À l\'instant'
  if (diffMins < 60) return `Il y a ${diffMins} min`
  if (diffHours < 24) return `Il y a ${diffHours} h`
  if (diffDays < 7) return `Il y a ${diffDays} j`
  return d.toLocaleDateString('fr-FR', { day: 'numeric', month: 'short' })
}

const getHousingLabel = (type) => {
  const labels = {
    maison: 'Maison',
    appartement: 'Appartement',
    villa: 'Villa',
    autre: 'Autre'
  }
  return labels[type] || type
}

const getStatusLabel = (status) => {
  const labels = {
    pending: 'En attente',
    accepted: 'Acceptée',
    rejected: 'Refusée',
    cancelled: 'Annulée'
  }
  return labels[status] || status
}

watch(tab, fetchRequests)
onMounted(fetchRequests)
</script>

